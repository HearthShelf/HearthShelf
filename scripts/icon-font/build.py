"""
Build the embedded icon font.

The full Material Symbols Rounded font is 5.3 MB (every icon, every axis). Loaded
as a separate file it arrived seconds after first paint on slow links (car
browsers, ship Wi-Fi), and once font-display's block period ran out every icon
showed as its ligature name ("play_arrow"). This script cuts it down to the
icons the app actually names, pins the axes the app never varies (wght 400,
GRAD 0, opsz 24; FILL stays variable for the filled variant), and writes the
result as a base64 data URI inside src/styles/icon-font.css. The CSS is part of
the render-blocking stylesheet, so icons are present on the very first paint.

Run: npm run icons   (needs Python 3 with fonttools and brotli)
`npm run icons:check` (Node, run before every build) fails if the source names
an icon that is not in the font, so a new icon cannot ship as plain text.
"""
import base64
import io
import json
import pathlib
import re
import sys

from fontTools.ttLib import TTFont
from fontTools.subset import Options, Subsetter
from fontTools.varLib.instancer import instantiateVariableFont

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = HERE / 'MaterialSymbolsRounded-full.woff2'
OUT_CSS = ROOT / 'src' / 'icon-font.css'
OUT_MANIFEST = HERE / 'icons.json'
OUT_ALL = HERE / 'all-icons.json'
SCAN_DIRS = [ROOT / 'src', ROOT / 'packages' / 'core' / 'src']
SCAN_EXT = {'.ts', '.tsx', '.css', '.html'}
# Quoted literals, plus bare text between tags (<span className="ms">home</span>).
TOKEN = re.compile(r"""['"`]([a-z0-9_]{2,})['"`]|>\s*([a-z0-9_]{2,})\s*<""")


def ligature_names(font):
    """Map each icon name (e.g. 'play_arrow') to its glyph."""
    # Upper and lower case letters share glyphs here; icon names are lower case.
    reverse = {}
    for code, glyph in font['cmap'].getBestCmap().items():
        ch = chr(code)
        if glyph not in reverse or ch.islower():
            reverse[glyph] = ch
    names = {}
    for lookup in font['GSUB'].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            if hasattr(sub, 'ExtSubTable'):
                sub = sub.ExtSubTable
            if getattr(sub, 'LookupType', None) != 4:
                continue
            for first, ligs in sub.ligatures.items():
                for lig in ligs:
                    parts = [first, *lig.Component]
                    if all(p in reverse for p in parts):
                        names[''.join(reverse[p] for p in parts)] = lig.LigGlyph
    return names


def used_tokens():
    found = set()
    for base in SCAN_DIRS:
        for path in base.rglob('*'):
            if path.suffix not in SCAN_EXT or 'node_modules' in path.parts:
                continue
            if path.name == 'icon-font.css':
                continue
            for a, b in TOKEN.findall(path.read_text(encoding='utf-8', errors='ignore')):
                found.add(a or b)
    return found


def main():
    font = TTFont(SOURCE)
    names = ligature_names(font)
    wanted = sorted(t for t in used_tokens() if t in names)
    if not wanted:
        sys.exit('no icon names found - refusing to write an empty font')

    # Drop every other ligature first. The subsetter keeps any ligature whose
    # component letters survive, and all letters survive, so without this it
    # would keep the whole icon set.
    keep = {names[n] for n in wanted}
    for lookup in font['GSUB'].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            if hasattr(sub, 'ExtSubTable'):
                sub = sub.ExtSubTable
            if getattr(sub, 'LookupType', None) == 4:
                for first in list(sub.ligatures):
                    sub.ligatures[first] = [l for l in sub.ligatures[first] if l.LigGlyph in keep]
                    if not sub.ligatures[first]:
                        del sub.ligatures[first]

    letters = set('abcdefghijklmnopqrstuvwxyz0123456789_')
    opts = Options()
    # The font drives its ligatures through rlig and rclt, not liga.
    opts.layout_features = ['rlig', 'rclt', 'liga', 'calt', 'ccmp']
    opts.flavor = 'woff2'
    opts.notdef_outline = False
    opts.name_IDs = []
    opts.drop_tables += ['DSIG']
    sub = Subsetter(opts)
    sub.populate(glyphs=[names[n] for n in wanted], unicodes=[ord(c) for c in letters])
    sub.subset(font)
    # Pin axes after subsetting: instancing first leaves lazily loaded gvar data
    # the subsetter cannot read.
    font = instantiateVariableFont(font, {'wght': 400, 'GRAD': 0, 'opsz': 24})

    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    data = buf.getvalue()
    b64 = base64.b64encode(data).decode('ascii')

    OUT_CSS.write_text(
        '/* GENERATED by scripts/icon-font/build.py (npm run icons) - do not edit.\n'
        f'   {len(wanted)} icons, {len(data)} bytes. Embedded so icons render on first\n'
        '   paint instead of after a separate font download. */\n'
        '@font-face {\n'
        "  font-family: 'Material Symbols Rounded';\n"
        f"  src: url(data:font/woff2;base64,{b64}) format('woff2');\n"
        '  font-weight: 100 700;\n'
        '  font-style: normal;\n'
        '  font-display: block;\n'
        '}\n',
        encoding='utf-8',
        newline='\n',
    )
    OUT_ALL.write_text(json.dumps(sorted(names), indent=0) + '\n', encoding='utf-8', newline='\n')
    OUT_MANIFEST.write_text(json.dumps(wanted, indent=0) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(wanted)} icons, {len(data):,} bytes woff2 (source {SOURCE.stat().st_size:,})')


if __name__ == '__main__':
    main()
